missing = []
for mod, pairs in T.items():
    p = MODS / mod / "main.js"
    s = p.read_text()
    for old, new in pairs:
        if old not in s:
            missing.append(f"{mod}: {old[:90]}")
            continue
        s = s.replace(old, new)
    p.write_text(s)
print("sem pendências" if not missing else "não casaram:", *missing, sep="\n  ")
